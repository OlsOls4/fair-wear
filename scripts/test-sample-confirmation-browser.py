"""Local browser regression for explicit sample-choice confirmation; no model calls."""
import os
from playwright.sync_api import sync_playwright, expect

base = os.environ.get("FAIRWEAR_TEST_URL", "http://127.0.0.1:3216")
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get("FAIRWEAR_TEST_BROWSER_PATH", "/usr/bin/chromium"), headless=True)
    context = browser.new_context(viewport={"width": 1280, "height": 900})
    page = context.new_page()
    page.goto(base + "/demo")
    carpet = page.locator('[data-finding-id="bedroom-carpet-0-0"]')
    oven = page.locator('[data-finding-id="kitchen-oven-0-0"]')
    progress = page.get_by_test_id("sample-choice-progress")
    expect(progress).to_contain_text("0 of 3")
    expect(carpet.locator("select")).to_have_value("Dispute")
    assert page.evaluate("sessionStorage.length") == 0
    confirm = carpet.get_by_role("button", name="Confirm Dispute:")
    confirm.focus()
    page.keyboard.press("Enter")
    expect(progress).to_contain_text("1 of 3")
    expect(carpet).to_contain_text("confirmed suggestion")
    page.reload()
    expect(progress).to_contain_text("1 of 3")
    undo = carpet.get_by_role("button", name="Undo confirmation:")
    undo.focus()
    page.keyboard.press("Space")
    expect(progress).to_contain_text("0 of 3")
    assert page.evaluate("sessionStorage.getItem('fair-wear:sample-review:v1')") is None
    carpet.get_by_role("button", name="Confirm Dispute:").click()
    oven.locator("select").select_option("Not claimed")
    expect(progress).to_contain_text("2 of 3")
    page.get_by_role("button", name="Cleaning (", exact=False).click()
    expect(progress).to_contain_text("2 of 3")
    page.get_by_role("button", name="Continue to case builder", exact=True).click()
    page.wait_for_url("**/case-builder*")
    expect(page.get_by_test_id("sample-review-handoff")).to_contain_text("2 selected sample responses carried over")
    expect(page.get_by_test_id("imported-review-response")).to_contain_text("Dispute")
    assert page.evaluate("sessionStorage.getItem('fair-wear:sample-case-transfer:v1')") is None
    page.reload()
    expect(page.get_by_test_id("sample-review-handoff")).to_have_count(0)
    page.goto(base + "/demo")
    expect(progress).to_contain_text("2 of 3")
    page.get_by_role("button", name="Reset suggested responses", exact=True).click()
    expect(progress).to_contain_text("0 of 3")
    page.reload()
    expect(progress).to_contain_text("0 of 3")
    page.set_viewport_size({"width": 375, "height": 812})
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    expect(carpet.get_by_role("button", name="Confirm Dispute:")).to_be_visible()
    context.close()
    browser.close()
print("Passed native Enter/Space confirmation, undo, mixed choices, filtered progress, reload/session, one-use transfer, reset and mobile overflow.")
