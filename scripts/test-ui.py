"""Optional browser regression checks against a running local production server.
Requires Python Playwright and Chromium. Set FAIRWEAR_TEST_BROWSER_PATH to use an
existing Chromium binary. No model calls or external-site interactions.
"""
import json
import os
from pathlib import Path
from urllib.parse import urlsplit
from playwright.sync_api import sync_playwright, expect

base = os.environ.get("FAIRWEAR_TEST_URL", "http://127.0.0.1:3200")
artifacts = Path(os.environ.get("FAIRWEAR_TEST_ARTIFACTS", "/tmp/fair-wear-ui"))
artifacts.mkdir(parents=True, exist_ok=True)
checks = 0

def passed(label):
    global checks
    checks += 1
    print(f"ok {label}")

with sync_playwright() as p:
    launch = {"headless": True}
    if os.environ.get("FAIRWEAR_TEST_BROWSER_PATH"):
        launch["executable_path"] = os.environ["FAIRWEAR_TEST_BROWSER_PATH"]
    browser = p.chromium.launch(**launch)
    context = browser.new_context(viewport={"width": 1280, "height": 900}, accept_downloads=True)
    page = context.new_page()
    external_requests = []
    context.on("request", lambda request: external_requests.append(request.url) if urlsplit(request.url).netloc != urlsplit(base).netloc else None)
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto(f"{base}/demo")
    expect(page.locator("select")).to_have_count(20)
    summary = page.get_by_test_id("decision-summary")
    expect(summary).to_contain_text("Agree: 2")
    expect(summary).to_contain_text("Dispute: 5")
    expect(summary).to_contain_text("Not claimed: 13")
    passed("20 findings and exact requested default distribution")

    def response(item):
        return page.locator(f'[data-finding-id="{item}"] select')

    expect(response("bathroom-bath-0-0")).to_have_value("Dispute")
    expect(response("bedroom-carpet-0-0")).to_have_value("Dispute")
    expect(response("living-room-carpet-0-1")).to_have_value("Agree")
    expect(response("kitchen-oven-0-0")).to_have_value("Agree")
    passed("mould, uncertain damage, high-confidence damage and ordinary cleaning defaults")
    expect(page.locator('[data-finding-id="bedroom-carpet-0-0"]')).to_contain_text("planted test expected fair wear")
    expect(page.get_by_role("region", name="Published evaluation on generated imagery")).to_contain_text("no finding card was produced")
    passed("known false positive and unsegmented miss disclosed")

    def review_shortcuts():
        for label, finding_id in [("Inspect a change", "living-room-carpet-0-1"), ("Inspect a model error", "bedroom-carpet-0-0")]:
            page.get_by_role("button", name="No change (13)", exact=True).click()
            target = page.locator(f'[data-finding-id="{finding_id}"]')
            expect(target).to_have_count(0)
            shortcut = page.get_by_role("button", name=label, exact=True)
            shortcut.focus()
            page.keyboard.press("Enter")
            expect(target).to_be_focused()
            expect(page.locator("select")).to_have_count(20)
            expect(page.get_by_role("button", name="All (20)", exact=True)).to_have_attribute("aria-pressed", "true")
            box = target.bounding_box()
            assert box and 0 <= box["y"] <= 48, box
            shortcut.click()
            expect(target).to_be_focused()
            page.screenshot(path=str(artifacts / f'{finding_id}-{page.viewport_size["width"]}.png'))
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")

    review_shortcuts()
    passed("keyboard shortcuts reveal filtered findings, focus visible targets, and allow repeat activation")
    opener = page.get_by_role("button", name="Open current draft", exact=True)
    opener.focus()
    page.keyboard.press("Enter")
    heading = page.get_by_role("heading", name="Current response draft", exact=True)
    expect(heading).to_be_focused()
    expect(opener).to_have_attribute("aria-expanded", "true")
    assert 0 <= heading.bounding_box()["y"] <= 24
    opener.click()
    expect(heading).to_be_focused()
    draft = page.get_by_test_id("current-draft")
    expect(draft).to_contain_text("DRAFT FOR REVIEW")
    expect(draft).to_contain_text("No amount is agreed")
    assert "I accept 71%" not in draft.inner_text()
    assert "I accept 100%" not in draft.inner_text()
    passed("current draft has no automatic percentage admissions")

    response("kitchen-oven-0-0").select_option("Dispute")
    expect(draft).to_contain_text("[kitchen-oven-0-0]: Dispute.")
    page.get_by_role("button", name="Damage (4)", exact=True).click()
    expect(page.get_by_role("button", name="Damage (4)", exact=True)).to_have_attribute("aria-pressed", "true")
    expect(page.locator("select")).to_have_count(4)
    expect(draft).to_contain_text("[kitchen-oven-0-0]: Dispute.")
    page.get_by_role("button", name="All (20)", exact=True).click()
    expect(response("kitchen-oven-0-0")).to_have_value("Dispute")
    passed("choices survive filtering and hidden findings remain in draft")

    response("living-room-carpet-0-1").select_option("Not claimed")
    expect(draft).not_to_contain_text("[living-room-carpet-0-1]")
    response("bedroom-wall-0-1").select_option("Agree")
    expect(draft).to_contain_text("[bedroom-wall-0-1]: Agree in principle")
    page.get_by_role("button", name="Close current draft", exact=True).click()
    expect(opener).to_be_focused()
    expect(opener).to_have_attribute("aria-expanded", "false")
    expect(draft).to_have_count(0)
    opener.click()
    expect(draft).to_contain_text("[bedroom-wall-0-1]: Agree in principle")
    passed("manual Not claimed and no-change overrides respected after reply reopen")

    with page.expect_download() as download_event:
        page.get_by_role("button", name="Download current draft (.txt)", exact=True).click()
    downloaded = download_event.value
    downloaded.save_as(artifacts / "current-draft.txt")
    assert (artifacts / "current-draft.txt").read_text() == draft.inner_text()
    passed("downloaded text matches current decisions")
    context.grant_permissions(["clipboard-read", "clipboard-write"])
    page.get_by_role("button", name="Copy current draft", exact=True).click()
    expect(page.get_by_role("status")).to_contain_text("Draft copied")
    assert page.evaluate("navigator.clipboard.readText()") == draft.inner_text()
    passed("clipboard text matches current decisions")

    archive = page.get_by_role("region", name="Original precomputed demo artifacts")
    expect(archive).to_contain_text("do not include your selected responses")
    expect(archive.get_by_role("link")).to_have_attribute("href", "/demo/fair-wear-evidence-pack.pdf")
    archive.get_by_text("View original Muse Spark reply (unchanged)", exact=True).click()
    expect(archive).to_contain_text("I accept 71%")
    expect(draft).not_to_contain_text("I accept 71%")
    passed("unchanged archive is separate from the current draft")

    page.get_by_role("button", name="Reset suggested responses", exact=True).click()
    expect(response("kitchen-oven-0-0")).to_have_value("Agree")
    expect(response("living-room-carpet-0-1")).to_have_value("Agree")
    expect(response("bedroom-wall-0-1")).to_have_value("Not claimed")
    review_shortcuts()
    passed("reset restores all suggested defaults and shortcuts remain usable")

    card = page.locator('[data-finding-id="bedroom-carpet-0-0"]')
    enlarge = card.get_by_role("button", name="Enlarge move-in evidence for bedroom carpet", exact=True)
    enlarge.click()
    dialog = page.get_by_role("dialog")
    expect(dialog).to_be_visible()
    expect(dialog.locator("img")).to_have_count(2)
    expect(dialog.locator("img").nth(0)).to_have_attribute("src", "/demo/flat/crops/bedroom-move_in-carpet-0.jpg")
    expect(dialog.locator("img").nth(1)).to_have_attribute("src", "/demo/flat/crops/bedroom-move_out-carpet-0.jpg")
    expect(dialog).to_contain_text("Framing and scale can differ; the divider is a visual aid, not an aligned measurement")
    expect(dialog.get_by_role("link")).to_have_count(2)
    report_slider = dialog.get_by_role("slider", name="Reveal move-in or move-out evidence for bedroom carpet", exact=True)
    expect(report_slider).to_have_value("50")
    report_slider.focus()
    page.keyboard.press("ArrowRight")
    expect(report_slider).to_have_value("51")
    page.keyboard.press("End")
    expect(report_slider).to_have_value("100")
    expect(dialog.locator(".evidence-comparison-after-tag")).not_to_be_visible()
    page.keyboard.press("Home")
    expect(report_slider).to_have_value("0")
    expect(dialog.locator(".evidence-comparison-before-tag")).not_to_be_visible()
    dialog.get_by_role("button", name="Compare", exact=True).click()
    expect(report_slider).to_have_value("50")
    bounds = dialog.locator(".evidence-comparison-scene").bounding_box()
    page.mouse.move(bounds["x"] + bounds["width"] / 2, bounds["y"] + bounds["height"] / 2)
    page.mouse.down()
    page.mouse.move(bounds["x"] + bounds["width"] * .75, bounds["y"] + bounds["height"] / 2, steps=5)
    page.mouse.up()
    assert 73 <= int(report_slider.input_value()) <= 77
    expect(report_slider).to_have_attribute("aria-valuetext", f"{report_slider.input_value()}% move-in, {100 - int(report_slider.input_value())}% move-out")
    assert dialog.locator(".evidence-comparison-layer img").evaluate_all("imgs => imgs.every(img => getComputedStyle(img).objectFit === 'contain' && img.complete && img.naturalWidth > 0)")
    # Opaque layer backgrounds prevent the other crop from bleeding through letterboxing.
    assert dialog.locator(".evidence-comparison-layer").evaluate_all("layers => layers.every(layer => getComputedStyle(layer).backgroundColor !== 'rgba(0, 0, 0, 0)')")
    page.screenshot(path=str(artifacts / "evidence-comparison-desktop.png"))
    passed("report comparison native keyboard, pointer reveal, complete contained crops, caveat and original links")
    dialog.get_by_role("button", name="Move-out", exact=True).click()
    expect(dialog.locator("img")).to_have_attribute("src", "/demo/flat/crops/bedroom-move_out-carpet-0.jpg")
    expect(dialog.get_by_role("slider")).to_have_count(0)
    dialog.get_by_role("button", name="Move-in", exact=True).click()
    expect(dialog.locator("img")).to_have_attribute("src", "/demo/flat/crops/bedroom-move_in-carpet-0.jpg")
    dialog.get_by_role("button", name="Compare", exact=True).click()
    expect(report_slider).to_have_value("50")
    page.screenshot(path=str(artifacts / "evidence-enlarged.png"))
    page.keyboard.press("Escape")
    expect(dialog).not_to_be_visible()
    expect(enlarge).to_be_focused()
    enlarge.click()
    expect(page.get_by_role("dialog").get_by_role("slider")).to_have_value("50")
    page.get_by_role("dialog").get_by_role("button", name="Close", exact=True).click()
    expect(page.get_by_role("dialog")).not_to_be_visible()
    enlarge.click()
    page.mouse.click(2, 2)
    expect(page.get_by_role("dialog")).not_to_be_visible()
    page.get_by_role("button", name="Inspect a change", exact=True).click()
    expect(page.locator('[data-finding-id="living-room-carpet-0-1"]')).to_be_focused()
    passed("evidence enlarge, image switch, Escape, focus return, reopen, Close, backdrop dismissal and next shortcut")
    page.evaluate("window.scrollTo(0, 0)")
    page.screenshot(path=str(artifacts / "demo-desktop.png"))

    response("kitchen-oven-0-0").select_option("Dispute")
    page.reload()
    expect(response("kitchen-oven-0-0")).to_have_value("Dispute")
    page.get_by_role("link", name="About this comparison", exact=True).click()
    page.get_by_role("button", name="Show sample findings", exact=True).click()
    expect(response("kitchen-oven-0-0")).to_have_value("Dispute")
    response("kitchen-oven-0-0").select_option("Not claimed")
    page.get_by_role("link", name="Go to the findings", exact=True).click()
    expect(response("kitchen-oven-0-0")).to_have_value("Not claimed")
    page.get_by_role("button", name="Reset suggested responses", exact=True).click()
    page.reload()
    expect(response("kitchen-oven-0-0")).to_have_value("Agree")
    passed("sample responses survive navigation and reload; reset clears them")
    page.goto(base)
    expect(page.get_by_text("Generated test images · Real model results.", exact=False)).to_be_visible()
    comparison = page.get_by_role("region", name="The sample flat", exact=True)
    slider = comparison.get_by_role("slider", name="Reveal move-in or move-out scene", exact=True)
    expect(slider).to_have_value("50")
    slider.focus()
    page.keyboard.press("ArrowRight")
    expect(slider).to_have_value("51")
    comparison.get_by_role("button", name="Move-out", exact=True).click()
    expect(slider).to_have_value("0")
    comparison.get_by_role("button", name="Move-in", exact=True).click()
    expect(slider).to_have_value("100")
    for room, filename, note in [("Bedroom", "bedroom", "planted as fair wear"), ("Bathroom", "bathroom", "not segmented"), ("Kitchen", "kitchen", "Neither suggestion establishes"), ("Living room", "living-room", "model flagged carpet damage")]:
        comparison.get_by_role("button", name=room, exact=True).click()
        expect(slider).to_have_value("50")
        expect(comparison.locator(".comparison-after")).to_have_attribute("src", f"/demo/flat/{filename}-move-out.jpg")
        expect(comparison.locator(".comparison-finding")).to_contain_text(note)
    bounds = comparison.locator(".comparison-scene").bounding_box()
    page.mouse.move(bounds["x"] + bounds["width"] / 2, bounds["y"] + bounds["height"] / 2)
    page.mouse.down()
    page.mouse.move(bounds["x"] + bounds["width"] * .75, bounds["y"] + bounds["height"] / 2, steps=5)
    page.mouse.up()
    assert 73 <= int(slider.input_value()) <= 77
    comparison.get_by_role("button", name="Compare", exact=True).click()
    expect(slider).to_have_value("50")
    page.screenshot(path=str(artifacts / "home-desktop-redesign.png"), full_page=True)
    passed("four-room comparison, native slider keyboard, full-scene presets, pointer dragging and reset")
    primary_link = page.get_by_role("link", name="Try the sample review", exact=True)
    primary_link.focus()
    page.keyboard.press("Enter")
    expect(page).to_have_url(f"{base}/demo")
    expect(page.get_by_role("heading", name="Findings board", exact=True)).to_be_visible()
    expect(page.locator("select")).to_have_count(20)
    expect(page.locator('input[type="file"]')).to_have_count(0)
    page.go_back()
    expect(page.get_by_role("heading", name="A fairer end to your tenancy.", exact=True)).to_be_visible()
    page.go_forward()
    expect(page.get_by_role("heading", name="Findings board", exact=True)).to_be_visible()
    passed("primary home link reaches findings in one keyboard activation; Back and Forward work")
    page.goto(base)
    page.locator("main").get_by_role("link", name="How it works", exact=True).click()
    expect(page.locator('input[type="file"]')).to_have_count(0)
    page.get_by_role("button", name="Show sample findings", exact=True).click()
    response("kitchen-oven-0-0").select_option("Dispute")
    page.get_by_role("button", name="Hide sample findings", exact=True).click()
    page.get_by_role("button", name="Show sample findings", exact=True).click()
    expect(response("kitchen-oven-0-0")).to_have_value("Dispute")
    passed("truthful sample flow has no file intake and preserves choices when hidden")
    page.go_back()
    expect(page.get_by_role("heading", name="A fairer end to your tenancy.", exact=True)).to_be_visible()
    page.go_forward()
    expect(page.get_by_role("heading", name="Explore a sample comparison", exact=True)).to_be_visible()
    passed("Back and Forward navigation works")

    page.set_viewport_size({"width": 390, "height": 844})
    page.goto(base)
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    page.screenshot(path=str(artifacts / "home-mobile.png"))
    page.get_by_role("link", name="Try the sample review", exact=True).click()
    expect(page).to_have_url(f"{base}/demo")
    review_shortcuts()
    page.evaluate("window.scrollTo(0, 0)")
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    page.screenshot(path=str(artifacts / "demo-mobile.png"))
    response("bathroom-bath-0-0").select_option("Agree")
    response("kitchen-oven-0-0").select_option("Dispute")
    review_shortcuts()
    page.get_by_role("button", name="Open current draft", exact=True).click()
    expect(page.get_by_role("heading", name="Current response draft", exact=True)).to_be_focused()
    expect(page.get_by_test_id("current-draft")).to_contain_text("[kitchen-oven-0-0]: Dispute.")
    page.screenshot(path=str(artifacts / "current-draft-mobile.png"))
    expect(page.get_by_test_id("current-draft")).to_contain_text("[bathroom-bath-0-0]: Agree in principle")
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    passed("mobile shortcuts, focus, layout and draft preserve changed choices without overflow")
    page.set_viewport_size({"width": 1280, "height": 900})
    page.add_style_tag(content="body { zoom: 2; }")
    review_shortcuts()
    page.get_by_role("button", name="Open current draft", exact=True).click()
    expect(page.get_by_role("heading", name="Current response draft", exact=True)).to_be_focused()
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    page.screenshot(path=str(artifacts / "current-draft-200-percent.png"))
    passed("200% content zoom keeps shortcuts, focused draft and page width usable")

    # Use an actual touch-enabled mobile context rather than just resizing desktop.
    mobile = browser.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True, device_scale_factor=2)
    touch_page = mobile.new_page()
    touch_page.on("pageerror", lambda error: errors.append(str(error)))
    touch_page.goto(f"{base}/demo")
    touch_opener = touch_page.get_by_role("button", name="Enlarge move-in evidence for bedroom carpet", exact=True)
    touch_opener.tap()
    touch_dialog = touch_page.get_by_role("dialog")
    touch_slider = touch_dialog.get_by_role("slider")
    expect(touch_slider).to_have_value("50")
    touch_bounds = touch_dialog.locator(".evidence-comparison-scene").bounding_box()
    touch_x, touch_y = touch_bounds["x"] + touch_bounds["width"] / 2, touch_bounds["y"] + touch_bounds["height"] / 2
    session = mobile.new_cdp_session(touch_page)
    session.send("Input.dispatchTouchEvent", {"type": "touchStart", "touchPoints": [{"x": touch_x, "y": touch_y}]})
    for fraction in [.55, .65, .75]:
        session.send("Input.dispatchTouchEvent", {"type": "touchMove", "touchPoints": [{"x": touch_bounds["x"] + touch_bounds["width"] * fraction, "y": touch_y}]})
    session.send("Input.dispatchTouchEvent", {"type": "touchEnd", "touchPoints": []})
    assert 73 <= int(touch_slider.input_value()) <= 77
    touch_dialog.get_by_role("button", name="Compare", exact=True).tap()
    expect(touch_slider).to_have_value("50")
    assert touch_dialog.evaluate("el => el.scrollWidth <= el.clientWidth")
    assert touch_page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    touch_page.screenshot(path=str(artifacts / "evidence-comparison-mobile.png"))
    touch_dialog.get_by_role("link", name="Open original move-out image (new tab)", exact=True).scroll_into_view_if_needed()
    expect(touch_dialog.get_by_role("link", name="Open original move-out image (new tab)", exact=True)).to_be_visible()
    touch_dialog.get_by_role("button", name="Move-out", exact=True).tap()
    expect(touch_dialog.locator("img")).to_have_count(1)
    touch_dialog.get_by_role("button", name="Close", exact=True).tap()
    expect(touch_dialog).not_to_be_visible()
    expect(touch_opener).to_be_focused()
    touch_page.set_viewport_size({"width": 320, "height": 568})
    touch_opener.tap()
    expect(touch_slider).to_have_value("50")
    assert touch_dialog.evaluate("el => el.scrollWidth <= el.clientWidth")
    touch_dialog.get_by_role("button", name="Close", exact=True).tap()
    passed("real mobile touch drag, reset, individual crop, reachable originals, 320px reflow, dismissal and reopening")
    mobile.close()
    assert external_requests == [], external_requests
    passed("all observed browser requests stayed local; no Meta API calls")
    assert errors == [], errors
    passed("no browser JavaScript errors")
    print(json.dumps({"checks": checks, "browser_errors": errors, "artifacts": str(artifacts)}))
    browser.close()
