"""Builds comparison cards (public/demo/cards/E*.jpg) and the evidence pack PDF from pre-computed findings + Muse Spark reply draft.
Free (no model calls). Run: python3 scripts/build-pack.py"""
import json, os, datetime
from PIL import Image, ImageDraw, ImageFont
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image as RLImage, Table, TableStyle, PageBreak, KeepTogether
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

D = "public/demo"
res = json.load(open(f"{D}/flat-results.json")); reply = json.load(open(f"{D}/reply-draft.json"))
ORDER = ["damage", "missing", "cleaning", "fair_wear", "added"]
LABEL = {"damage": "DAMAGE", "fair_wear": "FAIR WEAR & TEAR", "cleaning": "CLEANING", "missing": "MISSING", "added": "ADDED"}
COL = {"damage": (180, 35, 24), "fair_wear": (47, 125, 79), "cleaning": (183, 121, 31), "missing": (122, 61, 184), "added": (43, 95, 180)}
fl = sorted([f for f in res["findings"] if f["verdict"] != "no_change"], key=lambda f: ORDER.index(f["verdict"]))
assert len(fl) == len(reply["refs"]), "findings changed since reply draft was made; rerun make-reply.ts"
for i, f in enumerate(fl): f["ref"] = f"E{i+1}"; assert reply["refs"][i]["item"] == f["item"]

def font(sz, bold=False):
    for p in ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]:
        if os.path.exists(p): return ImageFont.truetype(p, sz)
    return ImageFont.load_default()

os.makedirs(f"{D}/cards", exist_ok=True)
for f in fl:
    a = Image.open("public" + f["before"]).convert("RGB"); b = Image.open("public" + f["after"]).convert("RGB")
    H = 420; a = a.resize((int(a.width*H/a.height), H)); b = b.resize((int(b.width*H/b.height), H))
    W = a.width + b.width + 60; card = Image.new("RGB", (W, H + 150), (250, 248, 244)); d = ImageDraw.Draw(card)
    card.paste(a, (20, 90)); card.paste(b, (40 + a.width, 90))
    d.text((20, 62), "MOVE-IN", fill=(102, 112, 133), font=font(18, True)); d.text((40 + a.width, 62), "MOVE-OUT", fill=(102, 112, 133), font=font(18, True))
    d.rounded_rectangle((20, 14, 20 + 250, 50), 18, fill=COL[f["verdict"]]); d.text((36, 21), LABEL[f["verdict"]], fill="white", font=font(18, True))
    d.text((290, 20), f'{f["ref"]}  {f["room"]} {f["item"]}', fill=(29, 36, 51), font=font(24, True))
    note = f'Simulated imagery (Muse Image). Tenant share if charged: {f["apportionmentPct"]}%' if f["verdict"] == "damage" else "Simulated imagery (Muse Image). Fair Wear"
    d.text((20, H + 105), note, fill=(102, 112, 133), font=font(16))
    card.save(f"{D}/cards/{f['ref']}.jpg", quality=88)
    f["card"] = f"/demo/cards/{f['ref']}.jpg"

ss = getSampleStyleSheet(); H1 = ParagraphStyle("h1", parent=ss["Title"], fontSize=24, alignment=0); B = ParagraphStyle("b", parent=ss["BodyText"], fontSize=10, leading=14)
S = ParagraphStyle("s", parent=B, textColor=colors.HexColor("#667085"), fontSize=8.5)
doc = SimpleDocTemplate(f"{D}/fair-wear-evidence-pack.pdf", pagesize=A4, leftMargin=18*mm, rightMargin=18*mm, topMargin=16*mm, bottomMargin=16*mm, title="Fair Wear evidence pack (simulated demo)", author="Fair Wear")
st = [Paragraph("Fair Wear: deposit evidence pack", H1),
      Paragraph(f'{res["property"]} · {res["tenancyYears"]}-year tenancy · generated {datetime.date.today():%d %B %Y}', B),
      Paragraph("DEMO PACK. All rooms and damage are generated by Muse Image and labelled simulated. Findings were produced by SAM 3.1 (segmentation) and Muse Spark (judging) and are an aid for the tenant, not legal advice.", S), Spacer(1, 8)]
rows = [["Ref", "Item", "Verdict", "Tenant share"]] + [[f["ref"], f'{f["room"]} {f["item"]}', LABEL[f["verdict"]].title(), f'{f["apportionmentPct"]}%' if f["verdict"] in ("damage", "cleaning") else ("0%" if f["verdict"] == "fair_wear" else "-")] for f in fl]
t = Table(rows, colWidths=[18*mm, 70*mm, 45*mm, 30*mm]); t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1d2433")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e4e0d6")), ("FONTSIZE", (0, 0), (-1, -1), 9)]))
st += [t, Spacer(1, 6), Paragraph("Tenant share = share of a like-for-like repair a tenant could fairly bear after allowing for the item's useful life and the tenancy length (betterment principle). Cleaning is shown at 100% of reasonable cleaning cost.", S), Spacer(1, 10)]
for f in fl:
    im = Image.open(f"{D}/cards/{f['ref']}.jpg"); w = 170*mm
    st.append(KeepTogether([Paragraph(f'<b>{f["ref"]} · {f["room"]} {f["item"]}</b> · {LABEL[f["verdict"]].title()} · model confidence {round(f["confidence"]*100)}%', B),
        RLImage(f"{D}/cards/{f['ref']}.jpg", width=w, height=w*im.height/im.width), Paragraph(f["description"], B), Paragraph(f.get("guidanceNote", ""), S), Spacer(1, 10)]))
st += [PageBreak(), Paragraph("Draft reply to the landlord", ss["Heading2"]), Paragraph("Drafted by Muse Spark from the findings above. Review before sending.", S), Spacer(1, 6)]
for para in reply["text"].split("\n\n"): st.append(Paragraph(para.replace("\n", "<br/>").replace("&", "&amp;"), B)); st.append(Spacer(1, 4))
doc.build(st)
res["findings"] = res["findings"]; json.dump({"cards": [{"ref": f["ref"], "card": f["card"], "room": f["room"], "item": f["item"], "verdict": f["verdict"]} for f in fl]}, open(f"{D}/cards.json", "w"), indent=1)
print("ok", len(fl), os.path.getsize(f"{D}/fair-wear-evidence-pack.pdf"))
